/**
 * counter.js —— 计数器 Store（组合式 Setup Store）
 * ------------------------------------------------------------
 * 本文件演示 Pinia 组合式写法中最基础的状态管理。
 *
 * 学习目标：
 *   1. 掌握 Setup Store 的基本结构
 *   2. 理解 ref 如何定义响应式状态
 *   3. 理解 computed 如何定义派生数据
 *   4. 理解 return 在 Setup Store 中的作用
 *   5. 理解 persist 配置的作用
 */

// ======================================================================
// 1. 从 Vue 中导入组合式 API
// ======================================================================
// ref：创建响应式数据
// computed：创建计算属性（派生数据）
import { computed, ref } from 'vue'

// ======================================================================
// 2. 从 Pinia 中导入 defineStore
// ======================================================================
// defineStore 是 Pinia 提供的核心 API，用于定义一个 Store
import { defineStore } from 'pinia'

// ======================================================================
// 3. 定义 Store
// ======================================================================
// defineStore 接收两个参数：
//   第一个参数：Store 的唯一 ID（字符串），在 DevTools 中会用到
//   第二个参数：一个函数，这是 Setup Store 的写法
//
// Setup Store 的特点：
//   - 函数内部可以使用 ref、computed、watch 等组合式 API
//   - 最后必须通过 return 暴露数据和方法
//   - 组件中通过 useCounterStore() 获取 Store 实例
//
// 组件中使用方式：
//   import { useCounterStore } from './stores/counter'
//   const counterStore = useCounterStore()
//   counterStore.count          // 读取状态
//   counterStore.doubleCount    // 读取计算属性
//   counterStore.increment()   // 调用方法
export const useCounterStore = defineStore('counter', () => {
  // ==================================================================
  // 4. 定义响应式状态（state）
  // ==================================================================
  // 使用 ref 创建一个响应式数字，初始值为 0
  // ref 包装后的数据需要通过 .value 来读写
  const count = ref(0)

  // ==================================================================
  // 5. 定义计算属性（getters）
  // ==================================================================
  // 使用 computed 创建一个派生数据
  // 它会根据 count 的值自动计算，结果会被缓存
  // 当 count 变化时，doubleCount 会自动重新计算
  const doubleCount = computed(() => count.value * 2)

  // ==================================================================
  // 6. 定义方法（actions）
  // ==================================================================
  // 在 Setup Store 中，方法就是普通函数
  // 注意：这里使用箭头函数或普通函数都可以
  // 因为 Setup Store 中没有 this，直接通过闭包访问 count

  // 计数器加 1
  const increment = () => {
    count.value++
  }

  // 计数器减 1
  const decrement = () => {
    count.value--
  }

  // 计数器重置为 0
  const reset = () => {
    count.value = 0
  }

  // ==================================================================
  // 7. 通过 return 暴露数据和方法
  // ==================================================================
  // 只有 return 出去的内容，组件中才能访问
  // 没有 return 的内容，组件中无法使用
  return {
    count,        // 响应式状态
    doubleCount,  // 计算属性
    increment,    // 加 1 方法
    decrement,    // 减 1 方法
    reset,        // 重置方法
  }
}, {
  // ==================================================================
  // 8. 持久化配置
  // ==================================================================
  // persist 配置让 Store 中的数据自动保存到 localStorage
  // 刷新页面后，数据仍然存在
  //
  // 简单写法：
  //   persist: true
  //
  // 自定义写法：
  //   persist: {
  //     key: 'my-counter',  // 存储到 localStorage 时的键名
  //   }
  persist: {
    key: 'my-counter',
  },
})
