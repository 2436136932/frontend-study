/**
 * main.js —— 应用入口文件
 * ------------------------------------------------------------
 * 本文件负责：
 *   1. 创建 Vue 应用实例
 *   2. 创建并注册 Pinia 状态管理
 *   3. 注册 Pinia 持久化插件
 *   4. 挂载应用到页面
 *
 * 学习目标：
 *   - 理解 Vue3 应用的启动流程
 *   - 理解 Pinia 是如何全局注册的
 *   - 理解插件（plugin）在 Vue 中的注册方式
 */

// ======================================================================
// 1. 导入 Vue 核心函数
// ======================================================================
// createApp 是 Vue3 创建应用实例的工厂函数
// 替代了 Vue2 中 new Vue() 的写法
import { createApp } from 'vue'

// ======================================================================
// 2. 导入 Pinia 核心函数
// ======================================================================
// createPinia 用于创建一个 Pinia 实例
// 每个 Vue 应用只需要一个 Pinia 实例
import { createPinia } from 'pinia'

// ======================================================================
// 3. 导入 Pinia 持久化插件
// ======================================================================
// pinia-plugin-persistedstate 可以让 Store 中的数据自动保存到 localStorage
// 刷新页面后数据仍然存在
import piniaPluginPersistedstate from 'pinia-plugin-persistedstate'

// ======================================================================
// 4. 导入根组件和全局样式
// ======================================================================
// App.vue 是整个应用的根组件
import App from './App.vue'

// style.css 是全局样式文件
import './style.css'

// ======================================================================
// 5. 创建 Vue 应用实例
// ======================================================================
// createApp(App) 会返回一个应用实例
// 后续所有配置（插件、挂载等）都基于这个实例
const app = createApp(App)

// ======================================================================
// 6. 创建 Pinia 实例
// ======================================================================
// createPinia() 返回一个 Pinia 实例
// 这个实例会管理应用中所有的 Store
const pinia = createPinia()

// ======================================================================
// 7. 注册 Pinia 持久化插件
// ======================================================================
// pinia.use() 用于给 Pinia 注册插件
// 注册后，配置了 persist: true 的 Store 会自动保存数据到本地存储
pinia.use(piniaPluginPersistedstate)

// ======================================================================
// 8. 注册 Pinia 到 Vue 应用
// ======================================================================
// app.use(pinia) 让 Vue 应用知道要使用 Pinia
// 注册后，所有组件都可以通过 useXxxStore() 获取 Store 实例
app.use(pinia)

// ======================================================================
// 9. 挂载应用到页面
// ======================================================================
// app.mount('#app') 把 Vue 应用挂载到 index.html 中 id="app" 的元素上
// 挂载后，页面开始渲染，所有组件开始工作
app.mount('#app')
